import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../data/fee_demand_slip.dart';
import '../data/fee_setup_repository.dart';

/// Two demand-notice copies for every student, generated only from posted
/// unpaid charges. Does not record money or act as a payment receipt.
class FeeDemandSlipPdf {
  const FeeDemandSlipPdf._();

  static pw.Widget _table(
      List<String> headers,List<List<String>> rows)=>
    pw.TableHelper.fromTextArray(
      headers:headers,
      data:rows.isEmpty?[List<String>.filled(headers.length,'—')]:rows,
      headerStyle:pw.TextStyle(fontSize:8,fontWeight:pw.FontWeight.bold),
      cellStyle:const pw.TextStyle(fontSize:8),
      headerDecoration:const pw.BoxDecoration(color:PdfColors.grey200),
      cellPadding:const pw.EdgeInsets.all(4),
      border:pw.TableBorder.all(color:PdfColors.grey400,width:0.5));

  static String _minor(int value)=>FeeMoney.showMinor(value);

  static List<pw.Widget> _contents(
      FeeDemandBatch batch,FeeDemandStudent student,String copy) {
    final current=student.lines.where((x)=>!x.arrears).toList();
    final arrears=student.lines.where((x)=>x.arrears).toList();
    final generated=batch.generatedAtUtc.toIso8601String()
      .replaceFirst('T',' ').substring(0,16)+' UTC';
    return [
      pw.Row(mainAxisAlignment:pw.MainAxisAlignment.spaceBetween,
        children:[
          pw.Text('Supa Model School',
            style:pw.TextStyle(fontSize:17,fontWeight:pw.FontWeight.bold)),
          pw.Text(copy,style:pw.TextStyle(
            fontSize:10,fontWeight:pw.FontWeight.bold)),
        ]),
      pw.SizedBox(height:6),
      pw.Text('MONTHLY FEE DEMAND SLIP — NOT A PAYMENT RECEIPT',
        style:pw.TextStyle(fontSize:11,fontWeight:pw.FontWeight.bold)),
      pw.Text('Academic Year: '+batch.yearLabel+' | Billing Month: '+
        batch.month+' | Prepared: '+generated,
        style:const pw.TextStyle(fontSize:8)),
      pw.Divider(),
      _table(['Student Name','Admission / Registration','Class / Section'],[[
        student.name,student.registration,student.className+
          (student.sectionName==null?'':' / '+student.sectionName!),
      ]]),
      pw.SizedBox(height:10),
      pw.Text('Current Month - Unpaid Charges',
        style:pw.TextStyle(fontSize:11,fontWeight:pw.FontWeight.bold)),
      _table(['Category','Bill Month','Due On','Billed',
        'Already Paid','Amount Due'],[
        for(final row in current)[
          row.category,row.month,row.dueOn,
          _minor(row.billedMinor),_minor(row.paidMinor),_minor(row.dueMinor)],
      ]),
      pw.SizedBox(height:10),
      pw.Text('Previous Months - Unpaid Arrears',
        style:pw.TextStyle(fontSize:11,fontWeight:pw.FontWeight.bold)),
      if(!batch.includeArrears)
        pw.Text('Previous arrears excluded by selected print option.',
          style:const pw.TextStyle(fontSize:8))
      else
        _table(['Category','Bill Month','Due On','Billed',
          'Already Paid','Amount Due'],[
          for(final row in arrears)[
            row.category,row.month,row.dueOn,
            _minor(row.billedMinor),_minor(row.paidMinor),_minor(row.dueMinor)],
        ]),
      pw.SizedBox(height:14),
      _table(['Current Month Due','Prior Arrears Due',
        'Total Outstanding ('+batch.currency+')'],[[
          _minor(student.currentDueMinor),_minor(student.arrearsDueMinor),
          _minor(student.totalDueMinor),
      ]]),
      pw.SizedBox(height:20),
      pw.Text('Please pay the outstanding amount at the authorized '
        'school collection desk. Bring this slip for reference.',
        style:const pw.TextStyle(fontSize:9)),
      pw.SizedBox(height:12),
      pw.Row(mainAxisAlignment:pw.MainAxisAlignment.spaceBetween,
        children:[
          pw.Text('Prepared By: _____________________',
            style:const pw.TextStyle(fontSize:9)),
          pw.Text('Signature / Stamp: _____________________',
            style:const pw.TextStyle(fontSize:9)),
        ]),
      pw.SizedBox(height:12),
      pw.Text('This is a notice of outstanding posted fees as of printing, '
        'not proof of payment. Amounts can change after new payments or '
        'approved corrections. No fee is generated by printing this slip.',
        style:const pw.TextStyle(fontSize:8,color:PdfColors.grey700)),
    ];
  }

  /// Student+Office (default) prints two distinct copies per student.
  /// Optional copy mode is useful for reprinting without producing more dues.
  static Future<Uint8List> build(
      FeeDemandBatch batch,PdfPageFormat format,
      {String copy='both'}) async {
    if(!{'both','student','office'}.contains(copy)||
       batch.students.isEmpty||batch.totalDueMinor<=0){
      throw const FormatException('No valid demand slips to print');
    }
    if(batch.students.map((s)=>s.id).toSet().length!=
       batch.students.length){
      throw const FormatException('Duplicate students in demand slips');
    }
    final pdf=pw.Document(title:'Monthly fee demand slips '+batch.month,
      creator:'Supa Model School');
    void add(FeeDemandStudent student,String label) {
      if(student.lines.isEmpty||student.totalDueMinor<=0||
        student.lines.any((x)=>x.dueMinor<=0||
          x.billedMinor-x.paidMinor!=x.dueMinor)||
        student.lines.fold<int>(0,(sum,x)=>sum+x.dueMinor)!=
          student.totalDueMinor){
        throw const FormatException('Unreconciled student demand slip');
      }
      pdf.addPage(pw.MultiPage(
        pageFormat:format,maxPages:25,
        margin:const pw.EdgeInsets.all(32),
        build:(_)=>_contents(batch,student,label),
        footer:(context)=>pw.Row(
          mainAxisAlignment:pw.MainAxisAlignment.spaceBetween,
          children:[
            pw.Text(student.registration+' • '+label,
              style:const pw.TextStyle(fontSize:8)),
            pw.Text('Page '+context.pageNumber.toString()+
              ' of '+context.pagesCount.toString(),
              style:const pw.TextStyle(fontSize:7)),
          ])));
    }
    for(final student in batch.students){
      if(copy=='both'||copy=='student')add(student,'STUDENT COPY');
      if(copy=='both'||copy=='office')add(student,'OFFICE COPY');
    }
    return pdf.save();
  }
}
